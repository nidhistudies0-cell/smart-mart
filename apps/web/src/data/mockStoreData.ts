export function getProductById(id: string | number): Product | undefined {
  const cleanId = String(id).toLowerCase().replace(/^p/, "").trim();
  const numId = parseInt(cleanId, 10);
  if (!isNaN(numId)) {
    const byNum = ALL_PRODUCTS.find((p) => p.productId === numId);
    if (byNum) return byNum;
  }
  // Try slug / name match
  return ALL_PRODUCTS.find((p) => {
    const slug = p.productName.toLowerCase().replace(/[^a-z0-9]+/g, "-");
    return slug === cleanId || p.productName.toLowerCase() === cleanId;
  });
}
